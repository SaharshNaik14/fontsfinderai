const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const google = JSON.parse(readFileSync(join(root, 'src/data/google-fonts.json'), 'utf8'));
const freeIds = new Set(google.fonts.map((f) => f.id));
const seen = new Set();
const paid = [];
const errors = [];
for (const [name, foundry, price, category, freeAlt, url] of rows) {
	const id = slug(name);
	if (seen.has(id)) {
		errors.push(`duplicate id: ${id} (${name})`);
		continue;
	}
	seen.add(id);
	if (!freeIds.has(freeAlt)) errors.push(`unknown freeAlt "${freeAlt}" for ${name}`);
	paid.push({ id, name, foundry, price, category, freeAlt, url: url || `https://www.myfonts.com/search/${encodeURIComponent(name)}/fonts/` });
}

mkdirSync(join(root, 'src/data'), { recursive: true });
writeFileSync(join(root, 'src/data/paid-fonts.json'), JSON.stringify(paid, null, 1));
console.log(`wrote ${paid.length} paid fonts -> src/data/paid-fonts.json`);
if (errors.length) {
	console.error('ERRORS:');
	for (const e of errors) console.error('  ' + e);
	process.exit(1);
}